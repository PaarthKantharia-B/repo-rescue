/**
 * Classifies an issue candidate's PR activity status.
 */
export function classifyCandidatePRActivity(
  githubState: string,
  openPrCount: number,
  isApiError: boolean = false
): CandidateClassification {
  if (githubState === 'closed') {
    return 'INELIGIBLE';
  }
  if (isApiError) {
    return 'UNVERIFIED';
  }
  if (openPrCount > 0) {
    return 'OPEN_PR_IN_PROGRESS';
  }
  return 'OPEN_NO_PR';
}

/**
 * Assesses internal candidate quality rating (HIGH, MEDIUM, LOW) and provides reasoning.
 */
export function evaluateCandidateQuality(issue: {
  title: string;
  body?: string | null;
  labels?: string[];
  commentsCount?: number;
}): { quality: CandidateQuality; reasoning: string } {
  const bodyText = (issue.body || '').trim();
  const bodyLen = bodyText.length;
  const labels = (issue.labels || []).map((l) => l.toLowerCase());

  if (bodyLen < 80) {
    return {
      quality: 'LOW',
      reasoning: `Minimal body detail (${bodyLen} chars). Missing technical reproduction steps or context.`,
    };
  }

  const hasCodeBlocks = bodyText.includes('```') || bodyText.includes('`');
  const hasTechnicalKeywords = /error|trace|repro|stack|expected|actual|version|config|reproduce/i.test(bodyText);
  const hasHelpfulLabels = labels.some((l) =>
    ['bug', 'help wanted', 'good first issue', 'enhancement', 'confirmed', 'needs triage', 'type: bug'].includes(l)
  );

  if (bodyLen >= 200 && (hasCodeBlocks || hasTechnicalKeywords || hasHelpfulLabels)) {
    return {
      quality: 'HIGH',
      reasoning: `Detailed issue description (${bodyLen} chars) with technical context, code/log references, and clear scope.`,
    };
  }

  return {
    quality: 'MEDIUM',
    reasoning: `Standard issue report (${bodyLen} chars) with moderate descriptive context.`,
  };
}

/**
 * Returns a stable unique key for a candidate (e.g. "supabase/supabase#12345").
 */
export function getCandidateIdentityKey(repoFullName: string, githubNumber: number): string {
  return `${repoFullName.toLowerCase()}#${githubNumber}`;
}

/**
 * Upserts a candidate into an existing candidate list without duplicates.
 */
export function upsertCandidate(
  existingList: IssueCandidate[],
  newCandidate: IssueCandidate
): IssueCandidate[] {
  const key = getCandidateIdentityKey(newCandidate.repoFullName, newCandidate.githubNumber);
  const index = existingList.findIndex(
    (c) => getCandidateIdentityKey(c.repoFullName, c.githubNumber) === key || c.githubId === newCandidate.githubId
  );

  if (index >= 0) {
    const copy = [...existingList];
    copy[index] = {
      ...copy[index],
      ...newCandidate,
      updatedAt: newCandidate.updatedAt || new Date().toISOString(),
      discoveredAt: copy[index].discoveredAt || newCandidate.discoveredAt,
    };
    return copy;
  }

  return [...existingList, newCandidate];
}

