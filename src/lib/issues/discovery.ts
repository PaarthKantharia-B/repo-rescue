export function getSeedCandidatePool(): IssueCandidate[] {
  const now = new Date().toISOString();
  return SEED_CANDIDATE_POOL.map((c) => ({
    ...c,
    discoveredAt: now,
  }));
}

/**
 * Executes GitHub REST API discovery for target repositories.
 * Fallbacks cleanly to seed candidate pool if rate limit or network error occurs.
 */
export async function discoverIssuesFromGithub(
  repoConfig: TargetRepositoryConfig,
  token?: string
): Promise<IssueCandidate[]> {
  const headers: Record<string, string> = {
    'User-Agent': 'Repo-Rescue-Candidate-Discovery-V1',
    Accept: 'application/vnd.github.v3+json',
  };
  if (token) {
    headers['Authorization'] = `token ${token}`;
  }

  const apiUrl = `https://api.github.com/repos/${repoConfig.fullName}/issues?state=open&per_page=30&sort=updated`;

  try {
    const res = await fetchWithTimeout(apiUrl, { headers }, 15000);
    if (!res.ok) {
      console.warn(`[Discovery] GitHub API call returned status ${res.status} for ${repoConfig.fullName}. Using pre-verified fallback candidate pool.`);
      return getSeedCandidatePool().filter((c) => c.repoFullName.toLowerCase() === repoConfig.fullName.toLowerCase());
    }

    const rawData = await res.json();
    if (!Array.isArray(rawData)) {
      return getSeedCandidatePool().filter((c) => c.repoFullName.toLowerCase() === repoConfig.fullName.toLowerCase());
    }

    const now = new Date().toISOString();
    const candidates: IssueCandidate[] = [];

    for (const item of rawData) {
      // Filter out pull requests returned by /issues endpoint
      if (item.pull_request) continue;

      const labels = Array.isArray(item.labels) ? item.labels.map((l: any) => l.name || l) : [];
      const { quality, reasoning } = evaluateCandidateQuality({
        title: item.title,
        body: item.body,
        labels,
        commentsCount: item.comments,
      });

      // Simple heuristic for openPrCount from body or title reference if comments indicate open PR
      const openPrCount = item.comments > 3 ? 1 : 0;
      const classification = classifyCandidatePRActivity(item.state, openPrCount);

      const candidate: IssueCandidate = {
        id: `cand-${repoConfig.fullName.replace('/', '-')}-${item.number}`,
        githubId: item.id,
        githubNumber: item.number,
        repoFullName: repoConfig.fullName,
        title: item.title,
        body: item.body || '',
        url: item.html_url || `https://github.com/${repoConfig.fullName}/issues/${item.number}`,
        labels,
        language: repoConfig.language,
        ecosystem: repoConfig.ecosystem,
        githubState: item.state === 'closed' ? 'closed' : 'open',
        classification,
        openPrCount,
        mergedPrCount: 0,
        quality,
        qualityReasoning: reasoning,
        commentsCount: item.comments || 0,
        authorUsername: item.user?.login || 'ghost',
        createdAt: item.created_at || now,
        updatedAt: item.updated_at || now,
        discoveredAt: now,
      };

      candidates.push(candidate);
    }

    if (candidates.length === 0) {
      return getSeedCandidatePool().filter((c) => c.repoFullName.toLowerCase() === repoConfig.fullName.toLowerCase());
    }

    return candidates;
  } catch (err) {
    console.warn(`[Discovery] Network/API error for ${repoConfig.fullName}:`, err);
    return getSeedCandidatePool().filter((c) => c.repoFullName.toLowerCase() === repoConfig.fullName.toLowerCase());
  }
}

/**
 * File path helper for scripts/data/issue-candidates.json
 */
export function getCandidateFilePath(): string {
  return path.join(process.cwd(), 'scripts', 'data', 'issue-candidates.json');
}

/**
 * Saves candidate list to scripts/data/issue-candidates.json
 */
export function saveCandidatesToFile(candidates: IssueCandidate[], filePath?: string): void {
  const targetPath = filePath || getCandidateFilePath();
  const dir = path.dirname(targetPath);
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }
  fs.writeFileSync(targetPath, JSON.stringify(candidates, null, 2), 'utf-8');
}

/**
 * Loads candidate list from scripts/data/issue-candidates.json
 */
export function loadCandidatesFromFile(filePath?: string): IssueCandidate[] {
  const targetPath = filePath || getCandidateFilePath();
  if (!fs.existsSync(targetPath)) {
    return [];
  }
  try {
    const raw = fs.readFileSync(targetPath, 'utf-8');
    return JSON.parse(raw);
  } catch (e) {
    return [];
  }
}
